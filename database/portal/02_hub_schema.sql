-- Hub schema (PostgreSQL), database neondb of the bkesari-hub project.
-- Safe to run more than once: the app applies it on every start.
--
-- One bkesari ID (decision D-039, 17 Nov 2026; docs/design/bkesari-id.md).
-- A person signs in once at the hub (Google, the email code, or a built-in
-- administrator's username) into `users`, then asks for access to each
-- project. hub_projects, project_access, access_requests and audit_log hold
-- that: they were the shared ID's tables before 3 Nov 2026 and are back in use
-- (columns added below, nothing dropped). Each project still keeps its own
-- database and its own user row; the hub tells it who the person is in signed
-- headers. The hub admin's own login (hub_admin_*, the tiles, the banner and
-- the contact inbox) stays as it was.

CREATE TABLE IF NOT EXISTS hub_projects (
  key         VARCHAR(40)  PRIMARY KEY,
  name        VARCHAR(120) NOT NULL,
  path        VARCHAR(60)  NOT NULL,
  -- open: anyone; signed_in: any signed-in user; approval: signed in + approved;
  -- owner: the owner only, no request path.
  visibility  VARCHAR(12)  NOT NULL CHECK (visibility IN ('open','signed_in','approval','owner')),
  roles       TEXT         NOT NULL DEFAULT 'member',
  sort_order  INTEGER      NOT NULL DEFAULT 0
);

