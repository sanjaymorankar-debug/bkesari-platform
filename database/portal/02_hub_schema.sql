CREATE TABLE IF NOT EXISTS project_access (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     VARCHAR(80)  NOT NULL,
  email       VARCHAR(254) NOT NULL,
  project_key VARCHAR(40)  NOT NULL REFERENCES hub_projects(key),
  role        VARCHAR(40)  NOT NULL,
  status      VARCHAR(12)  NOT NULL DEFAULT 'active' CHECK (status IN ('active','revoked')),
  approved_by VARCHAR(254) NULL,
  created_at  TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
  UNIQUE (user_id, project_key)
);
CREATE INDEX IF NOT EXISTS idx_project_access_email ON project_access (lower(email));
-- user_id is users.id as text (rows from before 3 Nov 2026 hold Neon Auth ids and match nobody).
ALTER TABLE project_access ADD COLUMN IF NOT EXISTS approved_at   TIMESTAMPTZ  NULL;
ALTER TABLE project_access ADD COLUMN IF NOT EXISTS request_id    BIGINT       NULL;
ALTER TABLE project_access ADD COLUMN IF NOT EXISTS revoked_at    TIMESTAMPTZ  NULL;
ALTER TABLE project_access ADD COLUMN IF NOT EXISTS revoked_by    VARCHAR(254) NULL;
ALTER TABLE project_access ADD COLUMN IF NOT EXISTS revoke_reason VARCHAR(500) NULL;
-- A project's own second step (LadWani): NULL when there is none, else 'pending' or 'verified'.
ALTER TABLE project_access ADD COLUMN IF NOT EXISTS project_state VARCHAR(12)  NULL;
ALTER TABLE project_access ADD COLUMN IF NOT EXISTS updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now();
CREATE INDEX IF NOT EXISTS idx_project_access_user ON project_access (user_id, project_key);

CREATE TABLE IF NOT EXISTS access_requests (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     VARCHAR(80)  NOT NULL,
  email       VARCHAR(254) NOT NULL,
  project_key VARCHAR(40)  NOT NULL REFERENCES hub_projects(key),
  role_wanted VARCHAR(40)  NOT NULL,
  note        VARCHAR(500) NULL,
  status      VARCHAR(12)  NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','declined')),
  decided_by  VARCHAR(254) NULL,
  decided_at  TIMESTAMP(0) NULL,
  created_at  TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'utc')
);
-- One open request per person per project.
CREATE UNIQUE INDEX IF NOT EXISTS uq_access_requests_pending
  ON access_requests (user_id, project_key) WHERE status = 'pending';
ALTER TABLE access_requests ADD COLUMN IF NOT EXISTS role_granted   VARCHAR(40)  NULL;
ALTER TABLE access_requests ADD COLUMN IF NOT EXISTS decline_reason VARCHAR(500) NULL;
CREATE INDEX IF NOT EXISTS idx_access_requests_status ON access_requests (status, created_at);

-- Every access decision (request, approve, decline, revoke, role change, suspend,
-- grant). created_at is UTC; pages show it in IST.
CREATE TABLE IF NOT EXISTS audit_log (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor      VARCHAR(254) NOT NULL,
  action     VARCHAR(40)  NOT NULL,
  target     VARCHAR(254) NULL,
  detail     VARCHAR(500) NULL,
  created_at TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'utc')
);
CREATE INDEX IF NOT EXISTS idx_audit_log_target ON audit_log (target, id);

-- ---------------------------------------------------------------------------
-- The bkesari ID (D-039). The columns after `status` are the ones
-- portal/project-auth.js needs, which runs the sessions, the email code, the
-- built-in administrators' sign-in, CSRF, rate limits and lockout for it.
-- role: 'member'; 'admin' for an address on HUB_OWNER_EMAILS (approves access);
-- 'owner' for the built-in administrators (also ATIP, and the top role everywhere).

CREATE TABLE IF NOT EXISTS users (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email           VARCHAR(254) NULL,
  name            VARCHAR(120) NULL,
  picture         VARCHAR(500) NULL,
  google_sub      VARCHAR(255) NULL,
  status          VARCHAR(12)  NOT NULL DEFAULT 'active' CHECK (status IN ('active','suspended','deleted')),
  created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
  last_login_at   TIMESTAMPTZ  NULL,
  role            VARCHAR(20)  NOT NULL DEFAULT 'member',
  mobile          VARCHAR(10)  NULL,
  password_hash   VARCHAR(100) NULL,
  email_verified  BOOLEAN      NOT NULL DEFAULT FALSE,
  mobile_verified BOOLEAN      NOT NULL DEFAULT FALSE,
  failed_attempts INTEGER      NOT NULL DEFAULT 0,
  locked_until    TIMESTAMPTZ  NULL,
  settings        JSONB        NOT NULL DEFAULT '{}'::jsonb,
  migrated_from   VARCHAR(80)  NULL,
  CHECK (email IS NOT NULL OR mobile IS NOT NULL)
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_users_email ON users (lower(email)) WHERE email IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_users_mobile ON users (mobile) WHERE mobile IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_users_google_sub ON users (google_sub) WHERE google_sub IS NOT NULL;

CREATE TABLE IF NOT EXISTS hub_sessions (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id      BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  token_hash   CHAR(64)     NOT NULL UNIQUE,
  csrf         VARCHAR(64)  NOT NULL,
  created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
  last_seen_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
  expires_at   TIMESTAMPTZ  NOT NULL,
  ip           VARCHAR(45)  NULL,
  user_agent   VARCHAR(300) NULL
);
CREATE INDEX IF NOT EXISTS idx_hub_sessions_user ON hub_sessions (user_id);

CREATE TABLE IF NOT EXISTS hub_password_resets (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    BIGINT      NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  purpose    VARCHAR(10) NOT NULL DEFAULT 'reset' CHECK (purpose IN ('reset','verify')),
  token_hash CHAR(64)    NOT NULL UNIQUE,
  expires_at TIMESTAMPTZ NOT NULL,
  used_at    TIMESTAMPTZ NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS hub_otp_codes (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  target     VARCHAR(254) NOT NULL,
  purpose    VARCHAR(10)  NOT NULL,
  code_hash  CHAR(64)     NOT NULL,
  attempts   INTEGER      NOT NULL DEFAULT 0,
  expires_at TIMESTAMPTZ  NOT NULL,
  used_at    TIMESTAMPTZ  NULL,
  created_at TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_hub_otp_target ON hub_otp_codes (target, id);

CREATE TABLE IF NOT EXISTS hub_rate_limits (
  bucket       VARCHAR(200) PRIMARY KEY,
  hits         INTEGER      NOT NULL,
  window_start TIMESTAMPTZ  NOT NULL
);

-- Sign-in events of the bkesari ID (sign-in, failures, codes, sign-out).
CREATE TABLE IF NOT EXISTS hub_auth_audit_log (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    BIGINT       NULL,
  actor      VARCHAR(254) NULL,
  action     VARCHAR(40)  NOT NULL,
  detail     VARCHAR(500) NULL,
  ip         VARCHAR(45)  NULL,
  created_at TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------------
-- Hub admin accounts (portal/project-auth.js, authSchema('hub_admin_')).
