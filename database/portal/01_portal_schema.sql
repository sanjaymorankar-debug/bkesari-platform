-- bkesari.com portal database (Task Tracker + the ATIP read-only snapshot), PostgreSQL.
-- Same as portal/sql/schema.sql (the app also runs it on start). Safe to re-run.
--     psql "$PORTAL_DATABASE_URL" -v ON_ERROR_STOP=1 -f 01_portal_schema.sql

-- Task Tracker + ATIP snapshot schema for PostgreSQL (13 or newer).
-- Safe to run more than once: every statement is IF NOT EXISTS.
-- The app also runs this automatically on startup, inside a transaction that
-- holds an advisory lock, so two processes starting together cannot race.
--
-- Times are UTC. created_at / updated_at / received_at are written by the
-- server as "YYYY-MM-DD HH:MM:SS" (UTC) and read back as the same text, which
-- is why they are TIMESTAMP (without time zone) rather than TIMESTAMPTZ.

CREATE TABLE IF NOT EXISTS projects (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name          VARCHAR(200) NOT NULL,
  description   TEXT NULL,
  owner         VARCHAR(120) NULL,
  status        VARCHAR(30)  NOT NULL DEFAULT 'Not Started',
  planned_start DATE NULL,
  planned_end   DATE NULL,
  actual_start  DATE NULL,
  actual_end    DATE NULL,
  current_step  TEXT NULL,
  next_step     TEXT NULL,
  created_at    TIMESTAMP(0) NOT NULL,
  updated_at    TIMESTAMP(0) NOT NULL
);

CREATE TABLE IF NOT EXISTS tasks (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id    INTEGER NULL,
  title         VARCHAR(250) NOT NULL,
  description   TEXT NULL,
  owner         VARCHAR(120) NULL,
  status        VARCHAR(30)  NOT NULL DEFAULT 'Not Started',
  planned_start DATE NULL,
  planned_end   DATE NULL,
  actual_start  DATE NULL,
  actual_end    DATE NULL,
  current_step  TEXT NULL,
  next_step     TEXT NULL,
  created_at    TIMESTAMP(0) NOT NULL,
  updated_at    TIMESTAMP(0) NOT NULL,
  CONSTRAINT fk_tasks_project FOREIGN KEY (project_id) REFERENCES projects(id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS idx_tasks_project ON tasks (project_id);

-- Status-update comments for both projects and tasks.
-- created_at is set by the server (UTC) at the moment the comment is posted.
CREATE TABLE IF NOT EXISTS comments (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entity_type VARCHAR(10) NOT NULL,
  entity_id   INTEGER NOT NULL,
  body        TEXT NOT NULL,
  created_at  TIMESTAMP(0) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_comments_entity ON comments (entity_type, entity_id, id);

-- Latest read-only ATIP dashboard page, pushed from the ATIP machine
-- by ATIP-DEV's publish_snapshot.py. Only the newest row is kept.
CREATE TABLE IF NOT EXISTS atip_snapshots (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  html         TEXT NOT NULL,
  trade_date   VARCHAR(20) NULL,
  generated_at VARCHAR(40) NULL,
  received_at  TIMESTAMP(0) NOT NULL
);
