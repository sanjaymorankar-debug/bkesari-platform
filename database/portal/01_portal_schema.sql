-- TaskList + ATIP snapshot schema for PostgreSQL (13 or newer): the one-file
-- form of tasklist_schema.sql followed by atip_schema.sql (tests/schema-copy.test.js
-- checks they agree). Safe to run more than once: every statement is IF NOT EXISTS.
-- Safe to run more than once: every statement is IF NOT EXISTS.
-- The app also runs this automatically on startup, inside a transaction that
-- holds an advisory lock, so two processes starting together cannot race.
--
-- Times are UTC. created_at / updated_at / received_at are written by the
-- server as "YYYY-MM-DD HH:MM:SS" (UTC) and read back as the same text, which
-- is why they are TIMESTAMP (without time zone) rather than TIMESTAMPTZ.
-- Due dates and times are IST wall-clock values (DATE + TIME), as people say them.

-- TaskList's own accounts: users, sessions, password resets, one-time codes,
-- rate limits and audit log, in TaskList's own database (portal/project-auth.js,
-- authSchema('tl_')). No other project reads these tables.
CREATE TABLE IF NOT EXISTS tl_users (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email           VARCHAR(254) NULL,
  mobile          VARCHAR(10)  NULL,
  name            VARCHAR(120) NULL,
  password_hash   VARCHAR(100) NULL,
  role            VARCHAR(20)  NOT NULL DEFAULT 'member',
  status          VARCHAR(12)  NOT NULL DEFAULT 'active' CHECK (status IN ('active','pending','suspended')),
  email_verified  BOOLEAN      NOT NULL DEFAULT FALSE,
  mobile_verified BOOLEAN      NOT NULL DEFAULT FALSE,
  failed_attempts INTEGER      NOT NULL DEFAULT 0,
  locked_until    TIMESTAMPTZ  NULL,
  settings        JSONB        NOT NULL DEFAULT '{}'::jsonb,
  migrated_from   VARCHAR(80)  NULL,
  created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
  last_login_at   TIMESTAMPTZ  NULL,
  CHECK (email IS NOT NULL OR mobile IS NOT NULL)
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_tl_users_email ON tl_users (lower(email)) WHERE email IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_tl_users_mobile ON tl_users (mobile) WHERE mobile IS NOT NULL;

CREATE TABLE IF NOT EXISTS tl_sessions (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id      BIGINT       NOT NULL REFERENCES tl_users(id) ON DELETE CASCADE,
  token_hash   CHAR(64)     NOT NULL UNIQUE,
  csrf         VARCHAR(64)  NOT NULL,
  created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
  last_seen_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
  expires_at   TIMESTAMPTZ  NOT NULL,
  ip           VARCHAR(45)  NULL,
  user_agent   VARCHAR(300) NULL
);
CREATE INDEX IF NOT EXISTS idx_tl_sessions_user ON tl_sessions (user_id);

CREATE TABLE IF NOT EXISTS tl_password_resets (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    BIGINT      NOT NULL REFERENCES tl_users(id) ON DELETE CASCADE,
  purpose    VARCHAR(10) NOT NULL DEFAULT 'reset' CHECK (purpose IN ('reset','verify')),
  token_hash CHAR(64)    NOT NULL UNIQUE,
  expires_at TIMESTAMPTZ NOT NULL,
  used_at    TIMESTAMPTZ NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS tl_otp_codes (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  target     VARCHAR(254) NOT NULL,
  purpose    VARCHAR(10)  NOT NULL,
  code_hash  CHAR(64)     NOT NULL,
  attempts   INTEGER      NOT NULL DEFAULT 0,
  expires_at TIMESTAMPTZ  NOT NULL,
  used_at    TIMESTAMPTZ  NULL,
  created_at TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_tl_otp_target ON tl_otp_codes (target, id);

CREATE TABLE IF NOT EXISTS tl_rate_limits (
  bucket       VARCHAR(200) PRIMARY KEY,
  hits         INTEGER      NOT NULL,
  window_start TIMESTAMPTZ  NOT NULL
);

CREATE TABLE IF NOT EXISTS tl_audit_log (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    BIGINT       NULL,
  actor      VARCHAR(254) NULL,
  action     VARCHAR(40)  NOT NULL,
  detail     VARCHAR(500) NULL,
  ip         VARCHAR(45)  NULL,
  created_at TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS projects (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name          VARCHAR(200) NOT NULL,
  description   TEXT NULL,
  owner         VARCHAR(120) NULL,
  status        VARCHAR(30)  NOT NULL DEFAULT 'Not Started',
  planned_start DATE NULL,
  planned_end   DATE NULL,
  actual_start  DATE NULL,
  actual_end    DATE NULL,
  current_step  TEXT NULL,
  next_step     TEXT NULL,
  created_at    TIMESTAMP(0) NOT NULL,
  updated_at    TIMESTAMP(0) NOT NULL
);

CREATE TABLE IF NOT EXISTS tasks (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id    INTEGER NULL,
  title         VARCHAR(250) NOT NULL,
  description   TEXT NULL,
  owner         VARCHAR(120) NULL,
  status        VARCHAR(30)  NOT NULL DEFAULT 'Not Started',
  planned_start DATE NULL,
  planned_end   DATE NULL,
  actual_start  DATE NULL,
  actual_end    DATE NULL,
  current_step  TEXT NULL,
  next_step     TEXT NULL,
  created_at    TIMESTAMP(0) NOT NULL,
  updated_at    TIMESTAMP(0) NOT NULL,
  CONSTRAINT fk_tasks_project FOREIGN KEY (project_id) REFERENCES projects(id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS idx_tasks_project ON tasks (project_id);

-- Status-update comments for both projects and tasks.
-- created_at is set by the server (UTC) at the moment the comment is posted.
CREATE TABLE IF NOT EXISTS comments (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entity_type VARCHAR(10) NOT NULL,
  entity_id   INTEGER NOT NULL,
  body        TEXT NOT NULL,
  created_at  TIMESTAMP(0) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_comments_entity ON comments (entity_type, entity_id, id);

