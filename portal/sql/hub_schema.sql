-- One banner across the top of the home page, when active and in its window.
CREATE TABLE IF NOT EXISTS hub_announcements (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  message_en  VARCHAR(300) NOT NULL,
  message_mr  VARCHAR(300) NULL,
  message_hi  VARCHAR(300) NULL,
  kind        VARCHAR(8)   NOT NULL DEFAULT 'info' CHECK (kind IN ('info','warning','success','brand')),
  link        VARCHAR(200) NULL,
  active      BOOLEAN      NOT NULL DEFAULT TRUE,
  starts_at   TIMESTAMPTZ  NULL,
  ends_at     TIMESTAMPTZ  NULL,
  created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
  created_by  VARCHAR(254) NULL
);

-- The contact form. Spam is kept out by a CSRF token, a hidden field, a
-- minimum fill time and a rate limit per address (portal/hub.js).
CREATE TABLE IF NOT EXISTS hub_contact_messages (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        VARCHAR(120) NOT NULL,
  email       VARCHAR(254) NULL,
  mobile      VARCHAR(15)  NULL,
  topic       VARCHAR(20)  NOT NULL DEFAULT 'general',
  message     VARCHAR(4000) NOT NULL,
  lang        VARCHAR(2)   NULL,
  ip          VARCHAR(45)  NULL,
  status      VARCHAR(8)   NOT NULL DEFAULT 'new' CHECK (status IN ('new','read','closed')),
  created_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);
