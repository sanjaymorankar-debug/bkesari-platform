CREATE TABLE IF NOT EXISTS project_access (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     VARCHAR(80)  NOT NULL,
  email       VARCHAR(254) NOT NULL,
  project_key VARCHAR(40)  NOT NULL REFERENCES hub_projects(key),
  role        VARCHAR(40)  NOT NULL,
  status      VARCHAR(12)  NOT NULL DEFAULT 'active' CHECK (status IN ('active','revoked')),
  approved_by VARCHAR(254) NULL,
  created_at  TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
  UNIQUE (user_id, project_key)
);
CREATE INDEX IF NOT EXISTS idx_project_access_email ON project_access (lower(email));

CREATE TABLE IF NOT EXISTS access_requests (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     VARCHAR(80)  NOT NULL,
  email       VARCHAR(254) NOT NULL,
  project_key VARCHAR(40)  NOT NULL REFERENCES hub_projects(key),
  role_wanted VARCHAR(40)  NOT NULL,
  note        VARCHAR(500) NULL,
  status      VARCHAR(12)  NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','declined')),
  decided_by  VARCHAR(254) NULL,
  decided_at  TIMESTAMP(0) NULL,
  created_at  TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'utc')
);
-- One open request per person per project.
CREATE UNIQUE INDEX IF NOT EXISTS uq_access_requests_pending
  ON access_requests (user_id, project_key) WHERE status = 'pending';

CREATE TABLE IF NOT EXISTS audit_log (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor      VARCHAR(254) NOT NULL,
  action     VARCHAR(40)  NOT NULL,
  target     VARCHAR(254) NULL,
  detail     VARCHAR(500) NULL,
  created_at TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'utc')
);

-- ---------------------------------------------------------------------------
-- Hub admin accounts (portal/project-auth.js, authSchema('hub_admin_')).
-- No sign-up: the first admin comes from HUB_ADMIN_EMAIL + HUB_ADMIN_PASSWORD(_HASH)
-- or tools/hub_admin.mjs.

CREATE TABLE IF NOT EXISTS hub_admin_users (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email           VARCHAR(254) NULL,
  mobile          VARCHAR(10)  NULL,
  name            VARCHAR(120) NULL,
  password_hash   VARCHAR(100) NULL,
  role            VARCHAR(20)  NOT NULL DEFAULT 'member',
  status          VARCHAR(12)  NOT NULL DEFAULT 'active' CHECK (status IN ('active','pending','suspended')),
  email_verified  BOOLEAN      NOT NULL DEFAULT FALSE,
  mobile_verified BOOLEAN      NOT NULL DEFAULT FALSE,
  failed_attempts INTEGER      NOT NULL DEFAULT 0,
  locked_until    TIMESTAMPTZ  NULL,
  settings        JSONB        NOT NULL DEFAULT '{}'::jsonb,
  migrated_from   VARCHAR(80)  NULL,
  created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
  last_login_at   TIMESTAMPTZ  NULL,
  CHECK (email IS NOT NULL OR mobile IS NOT NULL)
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_hub_admin_users_email ON hub_admin_users (lower(email)) WHERE email IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_hub_admin_users_mobile ON hub_admin_users (mobile) WHERE mobile IS NOT NULL;

CREATE TABLE IF NOT EXISTS hub_admin_sessions (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id      BIGINT       NOT NULL REFERENCES hub_admin_users(id) ON DELETE CASCADE,
  token_hash   CHAR(64)     NOT NULL UNIQUE,
  csrf         VARCHAR(64)  NOT NULL,
  created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
  last_seen_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
  expires_at   TIMESTAMPTZ  NOT NULL,
  ip           VARCHAR(45)  NULL,
  user_agent   VARCHAR(300) NULL
);
CREATE INDEX IF NOT EXISTS idx_hub_admin_sessions_user ON hub_admin_sessions (user_id);

CREATE TABLE IF NOT EXISTS hub_admin_password_resets (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    BIGINT      NOT NULL REFERENCES hub_admin_users(id) ON DELETE CASCADE,
  purpose    VARCHAR(10) NOT NULL DEFAULT 'reset' CHECK (purpose IN ('reset','verify')),
  token_hash CHAR(64)    NOT NULL UNIQUE,
  expires_at TIMESTAMPTZ NOT NULL,
  used_at    TIMESTAMPTZ NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS hub_admin_otp_codes (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  target     VARCHAR(254) NOT NULL,
  purpose    VARCHAR(10)  NOT NULL,
  code_hash  CHAR(64)     NOT NULL,
  attempts   INTEGER      NOT NULL DEFAULT 0,
  expires_at TIMESTAMPTZ  NOT NULL,
  used_at    TIMESTAMPTZ  NULL,
  created_at TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_hub_admin_otp_target ON hub_admin_otp_codes (target, id);

CREATE TABLE IF NOT EXISTS hub_admin_rate_limits (
  bucket       VARCHAR(200) PRIMARY KEY,
  hits         INTEGER      NOT NULL,
  window_start TIMESTAMPTZ  NOT NULL
);

CREATE TABLE IF NOT EXISTS hub_admin_audit_log (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    BIGINT       NULL,
  actor      VARCHAR(254) NULL,
  action     VARCHAR(40)  NOT NULL,
  detail     VARCHAR(500) NULL,
  ip         VARCHAR(45)  NULL,
  created_at TIMESTAMPTZ  NOT NULL DEFAULT now()
);

