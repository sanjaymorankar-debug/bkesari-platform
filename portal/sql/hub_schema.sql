-- Hub schema (PostgreSQL): who may open which project.
-- Sign-in itself (users, sessions) lives in Neon Auth's own tables; these tables
-- only record what each signed-in person may open. Safe to run more than once.
-- A user is identified by their Neon Auth user id (text), never by a foreign key,
-- because the Neon Auth tables belong to Neon Auth.

CREATE TABLE IF NOT EXISTS hub_projects (
  key         VARCHAR(40)  PRIMARY KEY,
  name        VARCHAR(120) NOT NULL,
  path        VARCHAR(60)  NOT NULL,
  -- open: anyone; signed_in: any signed-in user; approval: signed in + approved;
  -- owner: the owner only, no request path.
  visibility  VARCHAR(12)  NOT NULL CHECK (visibility IN ('open','signed_in','approval','owner')),
  roles       TEXT         NOT NULL DEFAULT 'member',
  sort_order  INTEGER      NOT NULL DEFAULT 0
);

