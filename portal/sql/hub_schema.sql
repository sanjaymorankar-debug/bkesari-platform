-- Hub schema (PostgreSQL), database neondb of the bkesari-hub project.
-- Safe to run more than once.
--
-- Since 3 Nov 2026 every project signs its own people in (LadWani, Education
-- and TaskList each have their own users table in their own database). The hub
-- has NO end-user accounts: only its admins (hub_admin_*), who edit the tiles,
-- the announcement banner and read the contact form.
--
-- DEPRECATED, kept read-only for tools/migrate_shared_id.mjs: hub_projects,
-- project_access and access_requests held the old shared bkesari ID's
-- permissions (Neon Auth user ids, never foreign keys). Nothing writes them now.

CREATE TABLE IF NOT EXISTS hub_projects (
  key         VARCHAR(40)  PRIMARY KEY,
  name        VARCHAR(120) NOT NULL,
  path        VARCHAR(60)  NOT NULL,
  -- open: anyone; signed_in: any signed-in user; approval: signed in + approved;
  -- owner: the owner only, no request path.
  visibility  VARCHAR(12)  NOT NULL CHECK (visibility IN ('open','signed_in','approval','owner')),
  roles       TEXT         NOT NULL DEFAULT 'member',
  sort_order  INTEGER      NOT NULL DEFAULT 0
);

