-- ATIP snapshot schema (bk_atip). Safe to run more than once.
-- Times are UTC text 'YYYY-MM-DD HH:MM:SS' stored as TIMESTAMP.

-- Latest read-only ATIP dashboard page, pushed from the ATIP machine
-- by ATIP-DEV's publish_snapshot.py. Only the newest row is kept.
CREATE TABLE IF NOT EXISTS atip_snapshots (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  html         TEXT NOT NULL,
  trade_date   VARCHAR(20) NULL,
  generated_at VARCHAR(40) NULL,
  received_at  TIMESTAMP(0) NOT NULL
);
